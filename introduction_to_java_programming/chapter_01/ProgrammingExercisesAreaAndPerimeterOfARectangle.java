public class ProgrammingExercisesAreaAndPerimeterOfARectangle {
    public static void main(String[] args) {
        System.out.println("1.9 (Area and perimeter of a rectangle) " +
                "Write a program that displays the area and perimeter of a rectangle" +
                "with a width of 5.3 and height 8.6 using the following formula: _");
        System.out.println();
        System.out.println("Perimeter = 2 * (width + height)");
        System.out.println("Area = width * height");
        System.out.println();
        System.out.print("Area = ");
        System.out.println(5.3 * 8.6);
        System.out.print("Perimeter = ");
        System.out.println(2 * (5.3 + 8.6));
    }
}
